def initials_of(answer: str) -> str:
    """取每个汉字的拼音首字母，答案必须是纯中文短语。"""

    parts = lazy_pinyin(answer, style=Style.FIRST_LETTER, errors="ignore")
    return "".join(part for part in parts if part.isalpha()).lower()


def variants(statement: str, answer: str) -> list[str]:
    base = statement.strip().rstrip("。！？")
    prefixes = [""]
    if not base[0].isdigit() and not base.startswith("「") and not base.startswith(
        NO_PREFIX_STARTS
    ):
        prefixes = PREFIXES
    result = []
    for prefix in prefixes:
        if answer in prefix:
            continue
        for suffix in SUFFIXES:
            if answer in suffix:
                continue
            cleaned = suffix[:-1] if suffix.endswith("。") else suffix
            result.append(f"{prefix}{base}{cleaned}。")
    return result


def _rows_from_facts(facts: list[dict], seen: set[str]) -> list[dict]:
    rows: list[dict] = []
    for fact in facts:
        answer = fact["answer"]
        initials = initials_of(answer)
        if len(initials) != len(answer):
            raise ValueError(f"答案必须是纯中文短语: {answer!r} -> {initials!r}")
        for statement in fact["statements"]:
            if statement.count(answer) != 1:
                raise ValueError(f"原句必须恰好出现一次答案: {answer!r} in {statement!r}")
            for sentence in variants(statement, answer):
                if answer not in sentence:
                    raise ValueError(f"变体里丢了答案: {answer!r} in {sentence!r}")
                blanked = sentence.replace(answer, "____", 1)
                if (
                    answer in blanked
                    or blanked.count("____") != 1
                    or blanked in seen
                ):
                    continue
                seen.add(blanked)
                row = {
                    "sentence": blanked,
                    "initials": initials,
                    "answer": answer,
                    "source": fact["source"],
                }
                rows.append(row)
    return rows


def _select_rows(
    rows: list[dict], count: int, seed: int, id_prefix: str
) -> list[dict]:
    if len(rows) < count:
        raise SystemExit(f"可用题目不足：只有 {len(rows)} 道，需要 {count} 道")
    rng = random.Random(seed)
    by_answer: dict[str, list[dict]] = {}
    for row in rows:
        by_answer.setdefault(row["answer"], []).append(row)
    selected = [rng.choice(group) for group in by_answer.values()]
    chosen = {id(row) for row in selected}
    remaining = [row for row in rows if id(row) not in chosen]
    rng.shuffle(remaining)
    rows = selected + remaining[: count - len(selected)]
    rng.shuffle(rows)
    for index, row in enumerate(rows, start=1):
        row["id"] = f"{id_prefix}-{index:05d}"
    return rows


def build(count: int, seed: int) -> list[dict]:
    return _select_rows(_rows_from_facts(FACTS, set()), count, seed, "fb")


def main() -> None:
    parser = argparse.ArgumentParser(description="生成补句问答题库")
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent.parent
        / "nonebot_plugin_mantou_affection"
        / "resources"
        / "fill_blank_questions.json",
    )
    parser.add_argument("--count", type=int, default=DEFAULT_COUNT)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = parser.parse_args()

    rows = build(args.count, args.seed)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        json.dumps({"questions": rows}, ensure_ascii=False, separators=(",", ":")),
        encoding="utf-8",
    )
    print(f"wrote {len(rows)} questions to {args.out}")


if __name__ == "__main__":
    main()
